const LANG_KEY = "bogachuk-lang";

function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "uk" || saved === "en") return saved;
  return "en";
}

function t(key, lang = getLang()) {
  const dict = I18N[lang] || I18N.uk;
  return dict[key] ?? I18N.uk[key] ?? key;
}

function templateType(typeKey, lang = getLang()) {
  const dict = I18N[lang] || I18N.uk;
  return dict.types[typeKey] || typeKey;
}

function templateDesc(id, lang = getLang()) {
  const dict = I18N[lang] || I18N.uk;
  return dict.descs[id] || id;
}

function applyI18n(lang) {
  const dict = I18N[lang] || I18N.uk;
  document.documentElement.lang = lang;
  document.title = dict.metaTitle;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", dict.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || dict[key] == null) return;
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = dict[key];
    } else {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key && dict[key] != null) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key && dict[key] != null) el.setAttribute("aria-label", dict[key]);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key && dict[key] != null) el.setAttribute("title", dict[key]);
  });

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
  });
}
